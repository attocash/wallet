#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { generateNativeLogos } from "./lib/native-logo-assets.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const common = resolve(root, "composeApp/src/commonMain/composeResources/drawable");
const web = resolve(root, "composeApp/src/wasmJsMain/resources");
const logoSvg = readFileSync(resolve(common, "logo.svg"), "utf8");
const generatedNotice = "<!-- Generated by scripts/generate-logo-assets.mjs; edit commonMain/composeResources/drawable/logo.svg. -->\n";

if (spawnSync("magick", ["-version"], { stdio: "ignore" }).status !== 0) {
  throw new Error("ImageMagick with librsvg support is required to export logo assets.");
}
const formats = spawnSync("magick", ["-list", "format"], { encoding: "utf8" });
if (formats.status !== 0 || !/^\s+RSVG\*?\s+SVG\s+r/m.test(formats.stdout)) {
  throw new Error("ImageMagick must include the librsvg (RSVG) renderer to export logo assets.");
}
if (!logoSvg.includes('viewBox="-2.5 -3.2 61 61"') || !logoSvg.includes("</defs>")) {
  throw new Error("The canonical logo geometry changed; review maskable padding before exporting.");
}

// Preserve the mark's center (28, 27.3), adding equal padding on every side.
// The complete mark occupies about 76% of this square's diameter, inside the
// maskable icon's guaranteed central circle with diameter 80% of the canvas.
const paddedSvg = logoSvg.replace('viewBox="-2.5 -3.2 61 61"', 'viewBox="-8 -8.7 72 72"');
const maskableSvg = paddedSvg
  .replace("</defs>", '</defs>\n  <rect x="-8" y="-8.7" width="72" height="72" fill="#111113"/>');
// Monochrome consumers select the shape from alpha and supply their own colors.
const monochromeSvg = paddedSvg.replace(/fill="#[0-9a-fA-F]{6}"/g, 'fill="#FFFFFF"');

writeFileSync(resolve(web, "logo.svg"), generatedNotice + logoSvg);
writeFileSync(resolve(web, "logo-black.svg"), generatedNotice + logoSvg.replace(/fill="#[0-9a-fA-F]{6}"/g, 'fill="black"'));
writeFileSync(resolve(web, "logo-maskable.svg"), generatedNotice + maskableSvg);
writeFileSync(resolve(web, "logo-monochrome.svg"), generatedNotice + monochromeSvg);

for (const size of [192, 512]) {
  renderSvg(logoSvg, size, resolve(web, `logo-${size}.png`));
  renderSvg(maskableSvg, size, resolve(web, `logo-maskable-${size}.png`), { opaque: true });
  renderSvg(monochromeSvg, size, resolve(web, `logo-monochrome-${size}.png`));
}
renderSvg(maskableSvg, 180, resolve(web, "logo-touch-180.png"), { opaque: true });
renderSvg(logoSvg, 48, resolve(web, "logo.ico"));
renderSvg(logoSvg, 512, resolve(common, "app_logo.png"));
renderSvg(logoSvg, 256, resolve(common, "app_logo.ico"));
generateNativeLogos({ root, logoSvg, renderSvg });

console.log("Generated web, desktop, Android, and iOS logo assets from commonMain/composeResources/drawable/logo.svg.");
console.log("Regenerate the Compose social preview separately with scripts/generate-og-image.mjs.");

function renderSvg(svg, size, output, { opaque = false } = {}) {
  const sizedSvg = svg.replace(/<svg\b([^>]*)>/, (_, attributes) => {
    const sizedAttributes = attributes
      .replace(/\bwidth="[^"]*"/, `width="${size}"`)
      .replace(/\bheight="[^"]*"/, `height="${size}"`);
    return `<svg${sizedAttributes}>`;
  });
  const format = extname(output);
  const options = ["-background", "none", "rsvg:-", "-strip"];
  if (opaque) options.push("-alpha", "off", "-define", "png:color-type=2");
  if (format === ".ico") {
    const sizes = size === 48 ? "48,32,16" : "256,128,64,48,32,16";
    options.push("-define", `icon:auto-resize=${sizes}`);
  }
  if (format === ".webp") options.push("-define", "webp:lossless=true");
  const result = spawnSync("magick", [...options, output], { input: sizedSvg, encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`Failed to export ${output}: ${result.stderr || result.error?.message}`);
  }
}
