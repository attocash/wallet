import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ANDROID_RES = 'composeApp/src/androidMain/res';
const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

function requiredMatch(text, pattern, description) {
  const match = text.match(pattern);
  if (!match) throw new Error(`Cannot generate native icons: missing ${description}`);
  return match;
}

function sourceGeometry(logoSvg) {
  const viewBox = requiredMatch(logoSvg, /viewBox="([^"]+)"/, 'viewBox')[1]
    .trim().split(/[\s,]+/).map(Number);
  const source = requiredMatch(logoSvg, /<g id="atto-icon-source">([\s\S]*?)<\/g>/, 'source paths')[1];
  const paths = [...source.matchAll(/<path\b[^>]*\/>/g)].map(([tag]) => {
    const data = requiredMatch(tag, /\bd="([^"]+)"/, 'source path data')[1];
    const fill = requiredMatch(tag, /\bfill="([^"]+)"/, 'source path fill')[1];
    // SVG and Android both accept six-digit RGB. Reject other formats rather
    // than silently changing a color (eight-digit hex uses different ordering).
    if (!/^#[\da-f]{6}$/i.test(fill)) {
      throw new Error(`Native icons require six-digit RGB source path fills: ${fill}`);
    }
    return { data, fill };
  });
  const polygon = requiredMatch(logoSvg, /<polygon points="([^"]+)"/, 'octant clip polygon')[1]
    .trim().split(/\s+/).map((point) => point.split(',').map(Number));
  const reflection = requiredMatch(logoSvg, /matrix\(0 -1 -1 0 ([\d.]+) ([\d.]+)\)/, 'octant reflection');
  if (viewBox.length !== 4 || viewBox.some((value) => !Number.isFinite(value)) || viewBox[2] !== viewBox[3]) {
    throw new Error('Native icons require a square canonical viewBox');
  }
  if (paths.length === 0 || polygon.some((point) => point.length !== 2 || point.some((value) => !Number.isFinite(value)))) {
    throw new Error('Invalid canonical logo geometry');
  }
  const centerX = viewBox[0] + viewBox[2] / 2;
  const centerY = viewBox[1] + viewBox[3] / 2;
  if (Number(reflection[1]) !== centerX + centerY || Number(reflection[2]) !== centerX + centerY) {
    throw new Error('Native reflection must preserve the canonical logo center');
  }
  return { viewBox, paths, polygon, centerX, centerY };
}

function number(value) {
  return Number(value.toFixed(10)).toString();
}

function foregroundVector(geometry) {
  const { viewBox, paths, polygon, centerX, centerY } = geometry;
  // Android masks a 108dp adaptive layer. Keep the mark in the central 66dp
  // safe circle, with uniform scaling and the same center as the SVG. The
  // canonical mark fits in a circle smaller than its 61-unit viewBox width.
  const scale = 66 / viewBox[2];
  const clip = `${polygon.map(([x, y], index) => `${index ? 'L' : 'M'}${x},${y}`).join(' ')} Z`;
  const octant = (indent) => [
    `${indent}<clip-path android:pathData="${clip}" />`,
    ...paths.map(({ data, fill }) => `${indent}<path android:fillColor="${fill}" android:pathData="${data}" />`),
  ].join('\n');
  const quadrants = [0, 90, 180, 270].map((rotation) => `        <group android:rotation="${rotation}" android:pivotX="${centerX}" android:pivotY="${centerY}">
            <group>
${octant('                ')}
            </group>
            <!-- Reflect across the diagonal through the canonical center. -->
            <group android:rotation="90" android:scaleX="-1" android:pivotX="${centerX}" android:pivotY="${centerY}">
${octant('                ')}
            </group>
        </group>`).join('\n');
  // VectorDrawable has no SVG <use>; expand the eight octants here so the
  // checked-in vector is generated from the single canonical source geometry.
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-logo-assets.mjs; edit the canonical logo.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:scaleX="${number(scale)}" android:scaleY="${number(scale)}"
        android:translateX="${number(54 - centerX * scale)}" android:translateY="${number(54 - centerY * scale)}">
${quadrants}
    </group>
</vector>
`;
}

function nativeTile(logoSvg, background) {
  // Canonical SVG stays nested: its square viewBox preserves the mark's exact
  // symmetry. Native white tiles provide contrast without changing gold paths.
  const mark = logoSvg.replace(/<svg\b[^>]*>/, (opening) => opening
    .replace(/\bwidth="[^"]*"/, 'width="72"')
    .replace(/\bheight="[^"]*"/, 'height="72"')
    .replace('<svg ', '<svg x="14" y="14" '));
  return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="100" height="100" viewBox="0 0 100 100">${background}${mark}</svg>`;
}

export function generateNativeLogos({ root, logoSvg, renderSvg }) {
  const geometry = sourceGeometry(logoSvg);
  const output = (relative) => {
    const absolute = join(root, relative);
    mkdirSync(dirname(absolute), { recursive: true });
    return absolute;
  };
  const square = nativeTile(logoSvg, '<rect x="8" y="8" width="84" height="84" rx="8" fill="white"/>');
  const round = nativeTile(logoSvg, '<circle cx="50" cy="50" r="47" fill="white"/>');
  const store = nativeTile(logoSvg, '<rect width="100" height="100" fill="white"/>');
  for (const [density, size] of Object.entries(DENSITIES)) {
    renderSvg(square, size, output(`${ANDROID_RES}/mipmap-${density}/ic_launcher.webp`));
    renderSvg(round, size, output(`${ANDROID_RES}/mipmap-${density}/ic_launcher_round.webp`));
  }
  // Store and iOS artwork stays opaque and square; the platform supplies masks.
  renderSvg(store, 512, output('composeApp/src/androidMain/ic_launcher-playstore.png'), { opaque: true });
  renderSvg(store, 1024, output('iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/app-icon-1024.png'), { opaque: true });
  writeFileSync(output(`${ANDROID_RES}/drawable/ic_launcher_foreground.xml`), foregroundVector(geometry));
}
