#!/usr/bin/env node

// Manual numeric-reference maintenance, never invoked by an application build.
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const referenceNode = 'v24.18.0';
const referenceV8 = '13.6.233.17-node.50';
if (process.version !== referenceNode || process.versions.v8 !== referenceV8) {
  throw new Error(`Use reference Node ${referenceNode} / V8 ${referenceV8}; found ${process.version} / ${process.versions.v8}`);
}

// Shared tests verify these fixed graph averages against every bundled Kotlin graph.
const bases = [2, 6, 10, 26, 33, 52, 62, 10000, 440 / 95, 432 / 94, 76 / 15, 84 / 16, 444 / 96];

const literal = (value) => {
  if (value === Infinity) return 'Double.POSITIVE_INFINITY';
  const text = String(value);
  return text.includes('.') || text.includes('e') ? text : `${text}.0`;
};

const tables = bases.map((base) => {
  const values = Array.from({ length: 257 }, (_, exponent) => base ** exponent);
  const lines = values.map((value) => `                ${literal(value)},`).join('\n');
  return `            ${literal(base)} to doubleArrayOf(\n${lines}\n            ),`;
});
const output = `package cash.atto.wallet.password

// Generated by scripts/generate-password-math.mjs with Node ${process.version}, V8 ${referenceV8}.
// Each array contains the exact reference doubles for integer exponents 0 through 256.
// PasswordMathTest verifies every reference bit and all supported graph/scoring bases.
internal object ReferencePowerData {
    val values: Map<Double, DoubleArray> =
        mapOf(
${tables.join('\n')}
        )
}
`;
const target = new URL('../composeApp/src/commonMain/kotlin/cash/atto/wallet/password/ReferencePowerData.kt', import.meta.url);
writeFileSync(target, output);
console.log(`${bases.length} bases, ${bases.length * 257} powers; sha256 ${createHash('sha256').update(output).digest('hex')}`);

// A compact bitwise reference fingerprint used by the shared test to verify every generated table entry.
let fingerprint = 0xcbf29ce484222325n;
const bytes = Buffer.allocUnsafe(8);
for (const base of bases) {
  for (let exponent = 0; exponent <= 256; exponent++) {
    bytes.writeDoubleLE(base ** exponent);
    fingerprint = BigInt.asUintN(64, (fingerprint ^ bytes.readBigUInt64LE()) * 0x100000001b3n);
  }
}
console.log(`Reference fingerprint: 0x${fingerprint.toString(16)}`);
